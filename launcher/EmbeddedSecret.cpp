QByteArray aes128Ctr(const QByteArray& key, const QByteArray& iv, const QByteArray& data)
{
    if (key.size() != 16 || iv.size() != 16)
        return {};
    uint8_t rk[176];
    expandKey(reinterpret_cast<const uint8_t*>(key.constData()), rk);

    uint8_t counter[16];
    std::memcpy(counter, iv.constData(), 16);

    QByteArray out(data.size(), Qt::Uninitialized);
    for (qsizetype off = 0; off < data.size(); off += 16) {
        uint8_t block[16];
        encryptBlock(rk, counter, block);
        const qsizetype n = qMin<qsizetype>(16, data.size() - off);
        for (qsizetype i = 0; i < n; ++i)
            out[off + i] = static_cast<char>(static_cast<uint8_t>(data[off + i]) ^ block[i]);
        for (int i = 15; i >= 0; --i)  // 128-bit big-endian increment
            if (++counter[i] != 0)
                break;
    }
    return out;
}

QString decrypt(const QString& payloadBase64, const QString& keyBase64)
{
    if (payloadBase64.isEmpty() || keyBase64.isEmpty())
        return {};
    const QByteArray payload = QByteArray::fromBase64(payloadBase64.toUtf8());
    const QByteArray key = QByteArray::fromBase64(keyBase64.toUtf8());
    if (payload.size() <= 16 || key.size() != 16)
        return {};
    return QString::fromUtf8(aes128Ctr(key, payload.left(16), payload.mid(16)));
}

