inline uint8_t xtime(uint8_t x)
{
    return static_cast<uint8_t>((x << 1) ^ ((x >> 7) * 0x1b));
}

void expandKey(const uint8_t key[16], uint8_t rk[176])
{
    std::memcpy(rk, key, 16);
    uint8_t rcon = 1;
    for (int i = 16; i < 176; i += 4) {
        uint8_t t[4] = { rk[i - 4], rk[i - 3], rk[i - 2], rk[i - 1] };
        if (i % 16 == 0) {
            const uint8_t first = t[0];
            t[0] = static_cast<uint8_t>(kSbox[t[1]] ^ rcon);
            t[1] = kSbox[t[2]];
            t[2] = kSbox[t[3]];
            t[3] = kSbox[first];
            rcon = xtime(rcon);
        }
        for (int j = 0; j < 4; ++j)
            rk[i + j] = static_cast<uint8_t>(rk[i - 16 + j] ^ t[j]);
    }
}

void addRoundKey(uint8_t s[16], const uint8_t* k)
{
    for (int i = 0; i < 16; ++i)
        s[i] ^= k[i];
}

void subShift(uint8_t s[16])
{
    uint8_t t[16];
    for (int c = 0; c < 4; ++c)
        for (int r = 0; r < 4; ++r)
            t[4 * c + r] = kSbox[s[4 * ((c + r) % 4) + r]];
    std::memcpy(s, t, 16);
}

void mixColumns(uint8_t s[16])
{
    for (int c = 0; c < 4; ++c) {
        uint8_t* a = s + 4 * c;
        const uint8_t a0 = a[0], a1 = a[1], a2 = a[2], a3 = a[3];
        const uint8_t t = static_cast<uint8_t>(a0 ^ a1 ^ a2 ^ a3);
        a[0] = static_cast<uint8_t>(a0 ^ t ^ xtime(static_cast<uint8_t>(a0 ^ a1)));
        a[1] = static_cast<uint8_t>(a1 ^ t ^ xtime(static_cast<uint8_t>(a1 ^ a2)));
        a[2] = static_cast<uint8_t>(a2 ^ t ^ xtime(static_cast<uint8_t>(a2 ^ a3)));
        a[3] = static_cast<uint8_t>(a3 ^ t ^ xtime(static_cast<uint8_t>(a3 ^ a0)));
    }
}

void encryptBlock(const uint8_t rk[176], const uint8_t in[16], uint8_t out[16])
{
    uint8_t s[16];
    std::memcpy(s, in, 16);
    addRoundKey(s, rk);
    for (int round = 1; round < 10; ++round) {
        subShift(s);
        mixColumns(s);
        addRoundKey(s, rk + 16 * round);
    }
    subShift(s);
    addRoundKey(s, rk + 160);
    std::memcpy(out, s, 16);
}

